const SKIP_NAMES = new Set(['__pycache__', 'node_modules', '.DS_Store']);
const GENERATED = '<!-- Generated by tools/export/build.mjs from export.manifest.json. Edit the manifest, not this file. -->';

// Text (decided by content) is rewritten; licence files keep their exact legal text and binaries their
// bytes. Whatever is left unrewritten still goes through every gate.
function copyRewritten(srcRoot, dstRoot, owner, rel = '', skipTop = null) {
  const written = [];
  for (const ent of readdirSync(path.join(srcRoot, rel), { withFileTypes: true })) {
    if (SKIP_NAMES.has(ent.name) || (!rel && skipTop && skipTop.has(ent.name))) continue;
    const r = rel ? `${rel}/${ent.name}` : ent.name;
    if (ent.isDirectory()) { written.push(...copyRewritten(srcRoot, dstRoot, owner, r, skipTop)); continue; }
    const to = path.join(dstRoot, r);
    mkdirSync(path.dirname(to), { recursive: true });
    const buf = readFileSync(path.join(srcRoot, r));
    writeFileSync(to, fileKind(r, buf) === 'text' && !isLicenceFile(ent.name) ? rewriteText(buf.toString('utf8'), { owner }).text : buf);
    written.push(r);
  }
  return written;
}

// A verdict other than SAFE carries what the kit's triage made of it, with a link to that section;
// the triage gate keeps an item from shipping without one.
const plural = (n, one, many) => `${n} ${n === 1 ? one : many}`;
function triageNote(scan, t) {
  if (!scan || scan.recommendation === 'SAFE') return '';
  if (!t) return '; not triaged yet';
  const parts = [t.fp && plural(t.fp, 'false positive', 'false positives'), t.byDesign && `${t.byDesign} by design`, t.other && `${t.other} not cleared`].filter(Boolean);
  const read = t.findings === 1 ? '1 finding, read' : `${t.findings} findings, all read`;
  return `; ${read}: ${parts.join(', ')} ([triage](../../../tools/export/scan-triage.md#${t.anchor}))`;
}

function sourceMd(item, meta, scan, triage) {
  const origin = meta.thirdParty
    ? `Third-party, adapted by the studio. Upstream: ${item.upstream || (meta.upstreams.length ? meta.upstreams.join(' and ') : 'named in SKILL.md metadata')}.`
    // Only what readSkillMeta checks: a licence file at the top of the folder and the author line.
    : 'Written in the studio\'s own words. The kit counts it as the studio\'s own only because its folder holds no licence file, and its author line names no outside author and does not say "adapted by".';
  const licence = meta.licenceFile
    ? `\`${meta.licenceFile}\` in this folder${meta.licenceLine ? ` (${meta.licenceLine})` : ''}`
    : meta.thirdParty ? 'see upstream' : 'MIT, the kit\'s own [LICENSE](../../../LICENSE)';
  return sourceLines(item.id, {
    origin, licence, changes: item.changes || 'n/a', suits: item.suits || 'see the module page',
    where: `${item.pack}${item.module ? ` / ${item.module}` : ''}`, last: lastScan(scan, triage),
  });
}

const lastScan = (scan, triage) => (scan
  ? `${scan.recommendation} (risk ${scan.score}/100), SkillSpector ${scan.version || ''} with --no-llm, ${scan.date}${triageNote(scan, triage)}`
  : 'not scanned yet (maintainers: `node tools/export/scan.mjs`)');

function sourceLines(id, f) {
  return [
    `# ${id}: source`, '', GENERATED, '',
    `- **Origin:** ${f.origin}`,
    `- **Licence:** ${f.licence}`,
    `- **What the studio changed:** ${f.changes}`,
    `- **Who it suits:** ${f.suits}`,
    `- **Pack / module:** ${f.where}`,
    `- **Last scan:** ${f.last}`,
    '', 'Before you take it, run it through `vet-and-adopt`: scan it yourself, then decide.', '',
  ].join('\n');
}

// A domain ships only when packShippable finds no licence file in it and no skill in it with an upstream or
// an "adapted" author line; without a credit file, the Origin line says that and no more. With one, the
// Origin and Licence lines name the licences of the adapted text and link the credit file.
const and = (xs) => (xs.length < 2 ? xs.join('') : `${xs.slice(0, -1).join(', ')} and ${xs[xs.length - 1]}`);
const creditLinks = (files) => and(files.map((f) => `[${f.split('/').pop()}](${f})`));
function packSourceMd(item, scan, triage, credit) {
  return sourceLines(item.id, {
    origin: credit
      ? `Adapts outside work: some text follows sources under ${and(credit.licences)}, credited in ${creditLinks(credit.files)}; the rest is the studio's own.`
      : 'Written in the studio\'s own words. The kit ships it only because no file in it carries an outside licence, an upstream, or an \'adapted\' author line.',
    licence: credit
      ? `The studio's text is MIT, the kit's own [LICENSE](../../../LICENSE); the credited parts keep their own licences (${and(credit.licences)}), listed in ${creditLinks(credit.files)}.`
      : 'MIT, the kit\'s own [LICENSE](../../../LICENSE)',
    changes: item.changes || 'n/a',
    suits: item.suits || `see its adoption card, [cards/pack-${item.id}.md](../../../cards/pack-${item.id}.md)`,
    where: 'a domain, installed as a pack of its own', last: lastScan(scan, triage),
  });
}

function where(it, upstreamOf) {
  if (it.kind === 'practice') return `[card](../cards/${it.id}.md)`;
  if (it.status === 'shipped') return it.kind === 'pack' ? `[packs/${it.id}](packs/${it.id}/SKILL.md)` : it.kind === 'agent' ? `[agents/${it.id}.md](agents/${it.id}.md)` : `[skills/${it.id}](skills/${it.id}/SOURCE.md)`;
  const up = it.upstream || upstreamOf[it.id];
  if (!up) return 'studio only, not in this kit';
  return /^https?:\/\//.test(up) ? `[upstream](${up})` : up;
}

// A domain is a pack itself, so it names no pack; the index groups the domains under "domains".
const packGroup = (it) => it.pack || (it.kind === 'pack' ? 'domains' : '-');

function indexMd(manifest, upstreamOf) {
  const rows = manifest.items.filter((it) => it.status !== 'private' && !(it.kind === 'pack' && it.status === 'withheld'))
    .sort((a, b) => `${packGroup(a)} ${a.module || ''} ${a.id}`.localeCompare(`${packGroup(b)} ${b.module || ''} ${b.id}`));
  return [
    '# Catalog index', '', GENERATED, '',
    'Every item the studio uses, by pack. `shipped` items are in this kit; `link-only` and `catalog-only` items are listed so you can find them; `drill-to-adopt` only offers the packs that fit you.', '',
    '| Item | Kind | Pack | Module | Status | Where |', '|---|---|---|---|---|---|',
    ...rows.map((it) => `| ${it.id} | ${it.kind} | ${packGroup(it)} | ${it.module || '-'} | ${it.status} | ${where(it, upstreamOf)} |`), '',
  ].join('\n');
}

// A skill that carries outside data names it in a NOTICE file in its folder; the notice lists it here with the
// licence the file states and the project it names.
function dataNotice(id, file, text) {
  const url = (text.match(/<(https?:\/\/[^>\s]+)>/) || text.match(/(https?:\/\/[^\s)>]+)/) || [])[1] || null;
  const licence = (text.match(/\b(?:Apache|MIT|BSD|MPL|Creative Commons)(?:[^.\n,;]|\.\d)*?(?:Licen[cs]e|\d\.\d)(?:[^.\n,;]|\.\d)*/) || [])[0] || null;
  return { id, upstream: url, licenceFile: file.replace(`catalog/skills/${id}/`, ''), licenceLine: licence ? `${licence} (data; see the notice file)` : null };
}

