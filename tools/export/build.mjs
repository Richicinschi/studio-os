      'Each domain below adapts some text from outside sources. Its credit file names every source, the source\'s licence and what was taken from it; the adapted parts keep those licences, and the studio\'s text in the domain is MIT. The last column lists the licences of the adapted text, each linked to its full text. Sources the credit file marks as not copied lent ideas, not text, so their licences are not listed.', '',
