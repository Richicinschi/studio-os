// tools/export/build.mjs
// Build the generated part of the kit from the hub: catalog/skills, catalog/agents,
// catalog/INDEX.md and docs/THIRD_PARTY_NOTICES.md. Hand-written files are never touched.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { rewriteText, fileKind, isLicenceFile } from './rules.mjs';
import { hubInventory, classify, readSkillMeta, validateManifest, isMenuItem, IMPORTANCE } from './manifest.mjs';
import { parseFrontmatter, splitFrontmatter } from './frontmatter.mjs';

const SKIP_NAMES = new Set(['__pycache__', 'node_modules', '.DS_Store']);
const GENERATED = '<!-- Generated by tools/export/build.mjs from export.manifest.json. Edit the manifest, not this file. -->';

// Text (decided by content) is rewritten; licence files keep their exact legal text and binaries their
// bytes. Whatever is left unrewritten still goes through every gate.
function copyRewritten(srcRoot, dstRoot, owner, rel = '') {
  const written = [];
  for (const ent of readdirSync(path.join(srcRoot, rel), { withFileTypes: true })) {
    if (SKIP_NAMES.has(ent.name)) continue;
    const r = rel ? `${rel}/${ent.name}` : ent.name;
    if (ent.isDirectory()) { written.push(...copyRewritten(srcRoot, dstRoot, owner, r)); continue; }
    const to = path.join(dstRoot, r);
    mkdirSync(path.dirname(to), { recursive: true });
    const buf = readFileSync(path.join(srcRoot, r));
    writeFileSync(to, fileKind(r, buf) === 'text' && !isLicenceFile(ent.name) ? rewriteText(buf.toString('utf8'), { owner }).text : buf);
    written.push(r);
  }
  return written;
}

function sourceMd(item, meta, scan) {
  const origin = meta.thirdParty
    ? `Third-party, adapted by the studio. Upstream: ${item.upstream || (meta.upstreams.length ? meta.upstreams.join(' and ') : 'named in SKILL.md metadata')}.`
    : 'Studio-original: written in the studio, not adapted from an outside skill.';
  const licence = meta.licenceFile
    ? `\`${meta.licenceFile}\` in this folder${meta.licenceLine ? ` (${meta.licenceLine})` : ''}`
    : meta.thirdParty ? 'see upstream' : 'MIT, the kit\'s own [LICENSE](../../../LICENSE)';
  const last = scan
    ? `${scan.recommendation} (risk ${scan.score}/100), SkillSpector ${scan.version || ''} with --no-llm, ${scan.date}`
    : 'not scanned yet (maintainers: `node tools/export/scan.mjs`)';
  return [
    `# ${item.id}: source`, '', GENERATED, '',
    `- **Origin:** ${origin}`,
    `- **Licence:** ${licence}`,
    `- **What the studio changed:** ${item.changes || 'n/a'}`,
    `- **Who it suits:** ${item.suits || 'see the module page'}`,
    `- **Pack / module:** ${item.pack}${item.module ? ` / ${item.module}` : ''}`,
    `- **Last scan:** ${last}`,
    '', 'Before you take it, run it through `vet-and-adopt`: scan it yourself, then decide.', '',
  ].join('\n');
}

function where(it, upstreamOf) {
  if (it.kind === 'practice') return `[card](../cards/${it.id}.md)`;
  if (it.status === 'shipped') return it.kind === 'agent' ? `[agents/${it.id}.md](agents/${it.id}.md)` : `[skills/${it.id}](skills/${it.id}/SOURCE.md)`;
  const up = it.upstream || upstreamOf[it.id];
  if (!up) return 'studio only, not in this kit';
  return /^https?:\/\//.test(up) ? `[upstream](${up})` : up;
}

function indexMd(manifest, upstreamOf) {
  const rows = manifest.items.filter((it) => it.status !== 'private')
    .sort((a, b) => `${a.pack} ${a.module || ''} ${a.id}`.localeCompare(`${b.pack} ${b.module || ''} ${b.id}`));
  return [
    '# Catalog index', '', GENERATED, '',
    'Every item the studio uses, by pack. `shipped` items are in this kit; `link-only` and `catalog-only` items are listed so you can find them; `drill-to-adopt` only offers the packs that fit you.', '',
    '| Item | Kind | Pack | Module | Status | Where |', '|---|---|---|---|---|---|',
    ...rows.map((it) => `| ${it.id} | ${it.kind} | ${it.pack} | ${it.module || '-'} | ${it.status} | ${where(it, upstreamOf)} |`), '',
  ].join('\n');
}

function noticesMd(entries) {
  return [
    '# Third-party notices', '', GENERATED, '',
    'The kit is MIT-licensed ([LICENSE](../LICENSE)), except the skills below: adapted from outside sources, each keeps its own upstream licence, whose file is in its folder in `catalog/skills/`.', '',
    '| Skill | Upstream | Licence |', '|---|---|---|',
    ...entries.map((e) => `| ${e.id} | ${e.upstream || '-'} | ${e.licenceLine || e.licenceFile || '-'} |`), '',
    'Tools and plugins installed from upstream, not copied, are the `external` items in `export.manifest.json`.', '',
  ].join('\n');
}

// ---- The feature menu: importance, why and context cost per item, by module.
export const HEAVY_TOKENS = 1000;
const tokens = (bytes) => Math.ceil(bytes / 4);
const bytesOf = (s) => Buffer.byteLength(s, 'utf8');
const fmt = (n) => n.toLocaleString('en-US');

function sizeOf(p) {
  if (!statSync(p).isDirectory()) return statSync(p).size;
  return readdirSync(p).reduce((sum, f) => sum + sizeOf(path.join(p, f)), 0);
}

// A skill's or agent's description loads every session; its body only when it is used.
function describedCost(file) {
  const text = readFileSync(file, 'utf8');
  const { data } = parseFrontmatter(text);
  return { loads: 'every-session', everySessionTokens: tokens(bytesOf(String((data && data.description) || ''))), onDemandTokens: tokens(bytesOf(splitFrontmatter(text).body)) };
}

function costOf(it, hub, out) {
  if (it.kind === 'skill') return describedCost(path.join(hub, '.claude', 'skills', it.id, 'SKILL.md'));
  if (it.kind === 'agent') return describedCost(path.join(hub, '.claude', 'agents', `${it.id}.md`));
  if (it.kind === 'external') return { loads: it.loads, everySessionTokens: it.loads === 'every-session' ? it.everySessionTokens : 0, onDemandTokens: it.onDemandTokens ?? null };
  const missing = it.files.filter((f) => !existsSync(path.join(out, f)));
  if (missing.length) throw new Error(`practice:${it.id}: ${missing.join(', ')} is not in the kit`);
  const t = tokens(it.files.reduce((sum, f) => sum + sizeOf(path.join(out, f)), 0));
  // A practice whose files are not what loads (a hook's output, a short table in the front door)
  // states its own estimate.
  const every = Number.isInteger(it.everySessionTokens) ? it.everySessionTokens : it.loads === 'every-session' ? t : 0;
  const onDemand = Number.isInteger(it.onDemandTokens) ? it.onDemandTokens : it.loads === 'on-demand' ? t : 0;
  return { loads: it.loads, everySessionTokens: every, onDemandTokens: onDemand };
}

function moduleTitle(out, id) {
  const page = path.join(out, 'modules', id, 'README.md');
  return existsSync(page) ? String(parseFrontmatter(readFileSync(page, 'utf8')).data?.title || id) : id;
}

export function buildFeatures({ hub, out, manifest }) {
  const menu = manifest.items.filter(isMenuItem);
  const moduleDir = path.join(out, 'modules');
  const onDisk = existsSync(moduleDir) ? readdirSync(moduleDir).filter((d) => existsSync(path.join(moduleDir, d, 'README.md'))) : [];
  const ids = [...new Set([...onDisk, ...menu.map((it) => it.module)])].sort();
  const rank = (it) => IMPORTANCE.indexOf(byDefault(it.importance));
  const modules = ids.map((id) => ({
    id, title: moduleTitle(out, id),
    items: menu.filter((it) => it.module === id).sort((a, b) => rank(a) - rank(b) || a.id.localeCompare(b.id)).map((it) => {
      const cost = costOf(it, hub, out);
      return {
        id: it.id, kind: it.kind, ...(it.title ? { title: it.title } : {}), importance: it.importance, why: it.why,
        ...cost, heavy: cost.everySessionTokens >= HEAVY_TOKENS, card: `cards/${it.id}.md`, ...(it.files ? { files: it.files } : {}),
      };
    }),
  }));
  return { kit: manifest.kit, version: manifest.version, heavyTokens: HEAVY_TOKENS, modules, later: manifest.later || [] };
}

// importance and why are a string, or per profile { default, data?, ml?, software? }; the drill resolves
// them against the adopter's profiles, so the menu shows every value.
const byDefault = (v) => (typeof v === 'string' ? v : v.default);
function importanceLabel(v) {
  if (typeof v === 'string') return v;
  const groups = new Map();
  for (const [k, val] of Object.entries(v)) if (k !== 'default' && val !== v.default) groups.set(val, [...(groups.get(val) || []), k]);
  return [v.default, ...[...groups].map(([val, ks]) => `${val} for ${ks.join(', ')}`)].join('; ');
}
const whyLabel = (v) => (typeof v === 'string' ? v
  : [v.default, ...Object.entries(v).filter(([k]) => k !== 'default').map(([k, w]) => `For ${k}: ${w}`)].join(' '));

const KIND_LABEL = { skill: 'skill', agent: 'agent', practice: 'practice', external: 'outside tool' };
const loadsLabel = (it) => (it.kind === 'skill' || it.kind === 'agent'
  ? `description every session, body on demand (about ${fmt(it.onDemandTokens)})`
  : it.loads.replace('-', ' '));

function featuresMd(f) {
  const lines = [
    '# Feature menu', '', GENERATED, '',
    'Every item you can adopt from this kit, by module, with two flags:', '',
    '- **Importance:** `core` means the rest of the adoption depends on it; `recommended` fixes a problem most people have; `optional` fixes a problem only some have. The Why column says which problem.',
    `- **Context cost:** \`none\` runs outside Claude, like a git hook; \`on demand\` loads only when it is used, like a skill's body; \`every session\` loads before your first message, like an instruction file or a skill's description. Token counts are estimates (the size in bytes divided by 4), and an item at ${fmt(f.heavyTokens)} tokens or more every session is marked heavy.`, '',
    'Tick whole modules, or pick single items from any module. `drill-to-adopt` asks you and writes your answers to `adoption/features.md` in your setup. Each item has an adoption card, `cards/<item>.md`: how it is detected, what you are asked, what it needs, the steps, the check, the undo and what to watch out for.', '',
    'The kit\'s own skills, `drill-to-adopt`, `vet-and-adopt` and `setup-workspace`, are not on this menu: they run from the kit folder during the adoption and are never installed into your setup.', '',
  ];
  for (const m of f.modules) {
    lines.push(m.title === m.id ? `## \`${m.id}\`` : `## ${m.title} (\`${m.id}\`)`, '');
    if (!m.items.length) { lines.push('Nothing to install: this module is habits you read and apply from its page.', ''); continue; }
    lines.push('| Item | What it is | Importance | Why | Loads | Tokens every session |', '|---|---|---|---|---|---|');
    for (const it of m.items) {
      lines.push(`| ${it.id} | ${KIND_LABEL[it.kind]}${it.title ? `: ${it.title}` : ''} | ${importanceLabel(it.importance)} | ${whyLabel(it.why)} | ${loadsLabel(it)} | ${fmt(it.everySessionTokens)}${it.heavy ? ' (heavy)' : ''} |`);
    }
    const total = m.items.reduce((s, it) => s + it.everySessionTokens, 0);
    lines.push('', `Every session for this module: about ${fmt(total)} tokens (estimate).`, '');
  }
  lines.push('## Not in this version', '');
  for (const l of f.later) lines.push(`- **${l.title}** (heavy): ${l.why}`);
  lines.push('', 'The catalog-only skills, grouped by domain, are listed in [catalog/INDEX.md](INDEX.md); they are not on this menu.', '');
  return lines.join('\n');
}

// `owner` is the owner's first name (from owner.local.txt), rewritten to "the owner".
// The reviewed studio rewrite list (STUDIO_REWRITES in rules.mjs): studio pointers in shipped copies
// become generic wording, and a reference to a script the copy does not ship goes. An entry is an
// exact `phrase` or a section `pattern`, for one file or every shipped markdown file ('*'). An entry
// that matches nothing stops the build, so the list never goes stale unnoticed. An entry from the local
// list (rewrites.local.json) also names a `gone` term that must have left its file, and is reported by
// number only, never by its text.
const entryName = (r) => (r.localIndex ? `rewrites.local.json entry ${r.localIndex}` : `${r.file}: ${r.phrase || r.pattern}`);
function applyStudioRewrites(out, written, rewrites) {
  const used = new Set();
  const left = [];
  for (const rel of written.filter((r) => r.startsWith('catalog/') && r.endsWith('.md'))) {
    const file = path.join(out, rel);
    let text = readFileSync(file, 'utf8');
    const before = text;
    const mine = rewrites.map((r, i) => [r, i]).filter(([r]) => r.file === '*' || r.file === rel);
    for (const [r, i] of mine) {
      // A phrase in backticks loses them with it, so a path in code becomes plain words.
      const re = r.pattern ? new RegExp(r.pattern, 'g') : new RegExp(`(\`?)${r.phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\1`, 'g');
      if (re.test(text)) { used.add(i); text = text.replace(re, () => r.replacement); }
    }
    for (const [r] of mine) if (r.gone && text.toLowerCase().includes(r.gone.toLowerCase())) left.push(`${entryName(r)}: its term is still in ${rel}`);
    if (text !== before) writeFileSync(file, text);
  }
  return { stale: rewrites.filter((_, i) => !used.has(i)), left };
}

export function buildKit({ hub, out, manifest, scans = {}, owner, rewrites = [] }) {
  const errors = validateManifest(manifest);
  if (errors.length) throw new Error(`manifest invalid:\n- ${errors.join('\n- ')}`);
  const inv = hubInventory(hub);
  const { unclassified, missing } = classify(inv, manifest);
  if (unclassified.length || missing.length) {
    const lines = [];
    if (unclassified.length) lines.push(`unclassified hub items (add each to export.manifest.json): ${unclassified.join(', ')}`);
    if (missing.length) lines.push(`manifest items not in the hub: ${missing.join(', ')}`);
    throw new Error(lines.join('\n'));
  }
  const skillDir = (id) => path.join(hub, '.claude', 'skills', id);
  const metas = Object.fromEntries(inv.skills.map((id) => [id, readSkillMeta(skillDir(id))]));
  const upstreamOf = Object.fromEntries(Object.entries(metas).map(([id, m]) => [id, m.upstream]).filter(([, u]) => u));

  rmSync(path.join(out, 'catalog', 'skills'), { recursive: true, force: true });
  rmSync(path.join(out, 'catalog', 'agents'), { recursive: true, force: true });
  const written = [];
  const itemFiles = {};
  const notices = [];
  for (const it of manifest.items.filter((i) => i.status === 'shipped')) {
    if (it.kind === 'skill') {
      const dst = path.join(out, 'catalog', 'skills', it.id);
      const files = copyRewritten(skillDir(it.id), dst, owner).map((r) => `catalog/skills/${it.id}/${r}`);
      writeFileSync(path.join(dst, 'SOURCE.md'), sourceMd(it, metas[it.id], scans[it.id]));
      files.push(`catalog/skills/${it.id}/SOURCE.md`);
      const m = metas[it.id];
      if (m.thirdParty) notices.push({ id: it.id, upstream: it.upstream || m.upstreams.join(', ') || null, licenceFile: m.licenceFile, licenceLine: m.licenceLine });
      itemFiles[`skill:${it.id}`] = files;
      written.push(...files);
    } else if (it.kind === 'agent') {
      const rel = `catalog/agents/${it.id}.md`;
      mkdirSync(path.join(out, 'catalog', 'agents'), { recursive: true });
      writeFileSync(path.join(out, rel), rewriteText(readFileSync(path.join(hub, '.claude', 'agents', `${it.id}.md`), 'utf8'), { owner }).text);
      itemFiles[`agent:${it.id}`] = [rel];
      written.push(rel);
    }
  }
  const { stale, left } = applyStudioRewrites(out, written, rewrites);
  if (stale.length) throw new Error(`studio rewrite entries that no longer match (fix or remove them in rules.mjs or rewrites.local.json):\n- ${stale.map(entryName).join('\n- ')}`);
  if (left.length) throw new Error(`studio rewrites that left their term behind (widen the entry, or add one):\n- ${left.join('\n- ')}`);
  mkdirSync(path.join(out, 'catalog'), { recursive: true });
  writeFileSync(path.join(out, 'catalog', 'INDEX.md'), indexMd(manifest, upstreamOf));
  const features = buildFeatures({ hub, out, manifest });
  writeFileSync(path.join(out, 'catalog', 'features.json'), `${JSON.stringify(features, null, 2)}\n`);
  writeFileSync(path.join(out, 'catalog', 'FEATURES.md'), featuresMd(features));
  mkdirSync(path.join(out, 'docs'), { recursive: true });
  writeFileSync(path.join(out, 'docs', 'THIRD_PARTY_NOTICES.md'), noticesMd(notices));
  written.push('catalog/INDEX.md', 'catalog/features.json', 'catalog/FEATURES.md', 'docs/THIRD_PARTY_NOTICES.md');
  return { written, itemFiles, notices };
}
